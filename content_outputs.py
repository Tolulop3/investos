"""
content_outputs.py -- Additive content outputs feeding OkMoneyMatters
(added 2026-10-29, Tolulope-approved, freeze-safe: reads only, writes
only its own files plus one additive brief section; NO scoring, model,
gate, threshold, or universe logic lives here).

1) WEEKLY RECEIPTS PACK  (receipts/weekly_<window-end>.json + .md)
   Built from outcomes_log ONLY, at TRUE horizon (Data Dictionary
   semantics: outcomes_log = pick performance at intended horizon).
   signal_accuracy is deliberately NOT used -- its fixed 3/7/14-day
   direction checks are not performance. Averages are net of the 0.20%
   round-trip cost convention (COST_PCT, same as shadow_v43).
   Anchor: generated by the FRIDAY daily run. Window = the 7 calendar
   days ending the day before the run (Fri run -> previous Fri..Thu),
   so consecutive weekly windows tile with no gaps or overlaps, and the
   pack is identical across Friday's three runs.

2) DAILY PLAIN-ENGLISH MARKET DIGEST  (digest/daily_<date>.json + .md,
   plus brief["plain_english_digest"])
   Derived only from the brief's macro + market_regime sections.
   Framing is HARD-CODED education-only: no picks, no tickers, no
   return promises, no advice language. Deterministic templates, no
   LLM, $0.
"""

import json
import math
import os
from datetime import date, timedelta

COST_PCT = 0.20  # round-trip cost convention: net = gross - 0.20

RECEIPTS_ANCHOR_WEEKDAY = 4  # Friday (Mon=0) -- see module docstring


# ── shared helpers ────────────────────────────────────────────────────

def _is_num(v):
    return isinstance(v, (int, float)) and math.isfinite(v)


def _fin(v):
    """Finite-or-0.0 -- the same sanitization convention as
    outcome_tracker's 2026-10-27 fix (NaN is truthy, so `or 0` cannot
    catch it; historical FLAT rows carrying NaN returns count as 0.0)."""
    return float(v) if _is_num(v) else 0.0


def _load_outcomes(path="outcomes_log.json"):
    with open(path) as f:
        raw = json.load(f)
    return raw if isinstance(raw, list) else raw.get("outcomes", [])


def _stats(rows):
    """Win rate / average / PF over true-horizon-resolved rows, using
    outcome_tracker's conventions (wins / n with FLATs in the
    denominator; PF from sanitized return sums)."""
    if not rows:
        return None
    rets = [_fin(o.get("true_horizon_return")) for o in rows]
    wins = sum(1 for o in rows if o.get("true_horizon_outcome") == "WIN")
    win_sum = sum(r for r in rets if r > 0)
    loss_sum = sum(-r for r in rets if r < 0)
    avg_gross = sum(rets) / len(rows)
    # PF is None (rendered "--") when there are no losing returns to
    # divide by -- outcome_tracker prints 0.0 there, which reads as
    # "total failure" in a content artifact when it actually means
    # "no losses in the window".
    pf = round(win_sum / loss_sum, 2) if loss_sum else None
    return {
        "n": len(rows),
        "wins": wins,
        "win_rate": round(wins / len(rows) * 100, 1),
        "avg_return_gross": round(avg_gross, 3),
        "avg_return_net": round(avg_gross - COST_PCT, 3),
        "profit_factor": pf,
    }


# ── 1) Weekly Receipts Pack ───────────────────────────────────────────

def _pick_story(o):
    ret = _fin(o.get("true_horizon_return"))
    entry = o.get("entry_price")
    # outcomes rows do not store a true-horizon exit price; it is derived
    # from entry and return and LABELLED as derived.
    exit_px = round(entry * (1 + ret / 100), 2) if _is_num(entry) and entry > 0 else None
    return {
        "ticker": o.get("ticker"),
        "category": o.get("category"),
        "horizon_days": o.get("true_horizon_days"),
        "entry_date": o.get("signal_date"),
        "exit_date": o.get("true_horizon_date"),
        "entry_price": entry,
        "exit_price_derived": exit_px,
        "return_gross": round(ret, 2),
        "return_net": round(ret - COST_PCT, 2),
        "outcome": o.get("true_horizon_outcome"),
    }


def build_receipts_pack(outcomes, window_end):
    """window_end: datetime.date. Window = [window_end - 6d, window_end],
    over rows whose true_horizon_date (the date the true-horizon
    resolution landed) falls inside it."""
    start = window_end - timedelta(days=6)
    s_str, e_str = start.isoformat(), window_end.isoformat()
    in_window = [o for o in outcomes
                 if o.get("true_horizon_resolved")
                 and s_str <= str(o.get("true_horizon_date") or "") <= e_str]
    non_finite = sum(1 for o in in_window
                     if not _is_num(o.get("true_horizon_return")))

    by_category = {}
    for cat in sorted({o.get("category") for o in in_window if o.get("category")}):
        by_category[cat] = _stats([o for o in in_window
                                   if o.get("category") == cat])
    underwater = [c for c, s in by_category.items()
                  if s and s["avg_return_net"] < 0]

    best = max(in_window, key=lambda o: _fin(o.get("true_horizon_return")),
               default=None)
    worst = min(in_window, key=lambda o: _fin(o.get("true_horizon_return")),
                default=None)

    return {
        "pack": "investos_receipts_weekly",
        "window": {"start": s_str, "end": e_str},
        "basis": ("True-horizon resolutions from outcomes_log only "
                  "(Data Dictionary semantics). Net = gross - 0.20% "
                  "round-trip cost. Paper/tracked record -- not "
                  "investment advice."),
        "week": _stats(in_window) or {"n": 0, "wins": 0, "win_rate": None,
                                      "avg_return_gross": None,
                                      "avg_return_net": None,
                                      "profit_factor": None},
        "best_pick": _pick_story(best) if best else None,
        "worst_pick": _pick_story(worst) if worst else None,
        "by_category": by_category,
        "underwater_categories": underwater,
        "overall_book": _stats([o for o in outcomes
                                if o.get("true_horizon_resolved")]),
        "data_quality": {
            "non_finite_returns_in_window": non_finite,
            "note": ("Non-finite (NaN) returns in the window -- historical "
                     "FLAT rows from before the 2026-10-27 ingestion fix -- "
                     "are counted as 0.0."
                     if non_finite else "Clean window: every return finite."),
        },
    }


def receipts_markdown(pack):
    w = pack["window"]
    wk = pack["week"]
    ob = pack["overall_book"] or {}
    lines = [
        f"# InvestOS Receipts Pack -- week of {w['start']} to {w['end']}",
        "",
        (f"**{wk['n']} picks reached their true horizon this week.** "
         f"Win rate {wk['win_rate']}%, average return "
         f"**{wk['avg_return_net']:+.2f}% net** of the 0.20% cost "
         f"convention (gross {wk['avg_return_gross']:+.2f}%), profit "
         f"factor {wk['profit_factor'] if wk['profit_factor'] is not None else '-- (no losses)'}."
         if wk["n"] else
         "**No picks reached their true horizon this week.**"),
        "",
        (f"Running overall book (all {ob.get('n')} true-horizon "
         f"resolutions): win rate {ob.get('win_rate')}%, average "
         f"{ob.get('avg_return_net'):+.2f}% net."
         if ob.get("n") else "Running overall book: no resolutions yet."),
        "",
        "## By category",
        "",
        "| Category | Resolved | Win rate | Avg (net) | PF |",
        "|---|---|---|---|---|",
    ]
    for cat, s in pack["by_category"].items():
        flag = " -- UNDERWATER" if cat in pack["underwater_categories"] else ""
        pf = s["profit_factor"] if s["profit_factor"] is not None else "--"
        lines.append(f"| {cat}{flag} | {s['n']} | {s['win_rate']}% | "
                     f"{s['avg_return_net']:+.2f}% | {pf} |")
    if pack["underwater_categories"]:
        lines += ["",
                  "**Underwater this week:** "
                  + ", ".join(pack["underwater_categories"])
                  + " averaged negative after costs."]
    for label, key in (("Best resolved pick", "best_pick"),
                       ("Worst resolved pick", "worst_pick")):
        p = pack[key]
        if p:
            lines += ["",
                      f"## {label}: {p['ticker']} ({p['category']})",
                      f"{p['return_net']:+.2f}% net over its "
                      f"{p['horizon_days']}-day horizon -- entered "
                      f"{p['entry_date']} at {p['entry_price']}, resolved "
                      f"{p['exit_date']} at {p['exit_price_derived']} "
                      f"(exit price derived from entry + return)."]
    lines += ["",
              f"_Data quality: {pack['data_quality']['note']}_",
              "",
              "_Source: outcomes_log true-horizon resolutions only. "
              "Paper/tracked record -- not investment advice._"]
    return "\n".join(lines) + "\n"


def write_receipts_pack(outcomes=None, today=None, outdir="receipts"):
    """Generate the pack for the 7 days ending yesterday relative to
    `today` (the generation day). Returns [json_path, md_path]."""
    if outcomes is None:
        outcomes = _load_outcomes()
    today = today or date.today()
    window_end = today - timedelta(days=1)
    pack = build_receipts_pack(outcomes, window_end)
    os.makedirs(outdir, exist_ok=True)
    base = os.path.join(outdir, f"weekly_{window_end.isoformat()}")
    with open(base + ".json", "w") as f:
        json.dump(pack, f, indent=2, default=str)
    with open(base + ".md", "w") as f:
        f.write(receipts_markdown(pack))
    return [base + ".json", base + ".md"]


# ── 2) Daily plain-English market digest ──────────────────────────────

_MOOD_PLAIN = {
    "RISK_OFF": "cautious -- more focused on avoiding losses than on chasing gains",
    "RISK_ON": "confident -- comfortable taking on risk",
    "CAUTIOUS": "careful -- willing, but watching the exits",
    "CONSTRUCTIVE": "quietly optimistic",
    "NORMAL": "mixed -- no strong mood either way",
    "BEAR": "defensive -- expecting trouble",
    "BULL": "upbeat",
}


def build_plain_english_digest(brief, digest_date=None):
    mr = brief.get("market_regime") or {}
    macro = brief.get("macro") or {}
    digest_date = digest_date or brief.get("date") or ""

    # -- trend sentence (S&P 500 vs its long-term trend line) --
    pct = mr.get("pct_above_ma")
    spx = mr.get("spx_price")
    if _is_num(pct) and _is_num(spx):
        if pct >= 0:
            trend = (f"The S&P 500 -- the index that tracks 500 large "
                     f"U.S. companies -- closed at {spx:,.0f}, about "
                     f"{abs(pct):.1f}% above its long-term trend line. "
                     f"Above that line is what people mean by a bull "
                     f"market: prices rising over months, not just days.")
        else:
            trend = (f"The S&P 500 -- the index that tracks 500 large "
                     f"U.S. companies -- closed at {spx:,.0f}, about "
                     f"{abs(pct):.1f}% below its long-term trend line. "
                     f"Below that line is what people mean by a bear "
                     f"market: prices falling over months, not just days.")
    elif mr.get("regime"):
        trend = (f"The broad U.S. market's long-term trend is currently "
                 f"labelled {mr['regime']} by the system.")
    else:
        trend = "The broad U.S. market's trend data was unavailable today."

    # -- mood + headline themes --
    mood = _MOOD_PLAIN.get(str(macro.get("regime") or "").upper(),
                           "mixed -- no strong mood either way")
    hs = (macro.get("headline_summary") or {}).get("active_signals") or []
    themes = [s.get("signal") for s in
              sorted(hs, key=lambda s: -(s.get("confidence") or 0))
              if s.get("signal")][:3]
    mood_sentence = f"Today's news flow leans {mood}."
    if themes:
        mood_sentence += (f" The loudest themes in the headlines: "
                          f"{', '.join(themes)}.")

    # -- combined read --
    unified = str(brief.get("unified_regime") or "").upper()
    combined_map = {
        "RISK_ON": ("Put trend and headlines together and the combined "
                    "read is 'risk-on': conditions favour patience with "
                    "a plan over reacting to any single headline."),
        "RISK_OFF": ("Put trend and headlines together and the combined "
                     "read is 'risk-off': conditions favour caution "
                     "over chasing moves."),
    }
    sentences = [trend, mood_sentence]
    if unified in combined_map:
        sentences.append(combined_map[unified])
    paragraph = " ".join(sentences)

    # -- "what this means for normal money" (education only) --
    lines = []
    if _is_num(pct):
        if pct >= 0:
            lines.append("A bull trend describes the recent past. It is "
                         "not a forecast, and it has never once meant "
                         "'prices only go up from here.'")
        else:
            lines.append("A bear trend describes what has already "
                         "happened over months. It says nothing certain "
                         "about next month -- downtrends have ended "
                         "without any announcement, every time.")
    if str(macro.get("regime") or "").upper() == "RISK_OFF":
        lines.append("When the news turns defensive, prices often move "
                     "on fear and relief instead of on how businesses "
                     "are actually doing. That kind of noise is normal "
                     "-- it is most of what daily market news is.")
    if str(macro.get("regime") or "").upper() == "RISK_ON":
        lines.append("When investors feel confident, money moves "
                     "toward growth and away from safety. Confidence is "
                     "a mood, not a measurement -- it can reverse on "
                     "one bad headline.")
    signal_names = " ".join(list((macro.get("active_signals") or {}).keys())
                            + themes).lower()
    if "earning" in signal_names:
        lines.append("Earnings season is when companies publish their "
                     "real numbers -- sales, profit, debt. It is the "
                     "regular reality check behind the stories told "
                     "about stocks the rest of the time.")
    if any(k in signal_names for k in ("oil", "middle east", "geopolit",
                                       "energy")):
        lines.append("Trouble in oil-producing regions moves energy "
                     "prices first, and everything that runs on fuel "
                     "after that -- one reason it leads market news "
                     "even if you never think about oil.")
    lines.append("This digest is market vocabulary in plain English, "
                 "for learning only -- never a tip on what to buy or sell.")
    lines = lines[:5]

    return {
        "date": digest_date,
        "paragraph": paragraph,
        "what_it_means": lines,
        "themes": themes,
        "trend": {
            "regime": mr.get("regime"),
            "spx_price": spx,
            "pct_above_ma200": pct,
        },
        "news_mood": macro.get("regime"),
        "unified_regime": brief.get("unified_regime"),
        "articles_read": macro.get("articles_read"),
        "framing": "Education only -- not financial advice.",
    }


def digest_markdown(digest):
    lines = [f"# Market in Plain English -- {digest['date']}", "",
             digest["paragraph"], "", "## What this means for normal money",
             ""]
    lines += [f"- {l}" for l in digest["what_it_means"]]
    lines += ["", f"_{digest['framing']}_"]
    return "\n".join(lines) + "\n"


def write_daily_digest(brief, today=None, outdir="digest"):
    """Write digest/daily_<date>.json + .md; returns the digest dict."""
    today = today or date.today()
    digest = build_plain_english_digest(
        brief, digest_date=brief.get("date") or today.isoformat())
    os.makedirs(outdir, exist_ok=True)
    base = os.path.join(outdir, f"daily_{today.isoformat()}")
    with open(base + ".json", "w") as f:
        json.dump(digest, f, indent=2, default=str)
    with open(base + ".md", "w") as f:
        f.write(digest_markdown(digest))
    return digest


